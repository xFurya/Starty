const _kindWords = {'w': 'женщины', 'm': 'мужчины', 'p': 'пары', 'd': 'танцы'};

/// «Франция · женщины», «Россия · пары»; пусто — ничего не знаем.
String personLine(String nation, String kinds) {
  final parts = <String>[
    if (nation.isNotEmpty) countryNames[nation] ?? nation,
    [for (final k in kinds.split('')) if (_kindWords[k] != null) _kindWords[k]!].join(', '),
  ]..removeWhere((s) => s.isEmpty);
  return parts.join(' · ');
}
